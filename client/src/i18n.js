export function makeT(lang) {
  const dict = DICT[lang] || DICT.es;
  return (key, vars) => {
    let value = dict[key];
    if (value === undefined) return key;
    if (vars) for (const [name, v] of Object.entries(vars)) value = value.replaceAll(`{${name}}`, String(v));
    return value;
  };
}
